import type {
    CreativeSkill,
    CreativeSkillKind,
    CreativeSkillTarget,
} from "@/lib/creative-skills";

type SkillSeed = [
    id: string,
    name: string,
    shortName: string,
    target: CreativeSkillTarget,
    kind: CreativeSkillKind,
    tags: string[],
    ratio: string,
    description: string,
    direction: string,
    camera: string,
    finish: string,
    constraints: string,
    duration?: number,
];

const clean = (brief: string) => brief.trim().replace(/\s+/g, " ");

function makeSkill(seed: SkillSeed): CreativeSkill {
    const [
        id,
        name,
        shortName,
        target,
        kind,
        tags,
        defaultAspectRatio,
        description,
        direction,
        camera,
        finish,
        constraints,
        defaultDuration,
    ] = seed;
    const video = target === "video";
    return {
        id,
        name,
        shortName,
        target,
        kind,
        tags,
        defaultAspectRatio,
        description,
        defaultDuration,
        sourceInspiration: "原创模板 · 公共视觉艺术与提示工程方法",
        buildPrompt: (brief) =>
            [
                `${video ? "视频主题" : "创作目标"}：${clean(brief)}。`,
                `${video ? "导演与动作设计" : "风格与美术方向"}：${direction}。`,
                `${video ? "镜头与时间推进" : "构图与镜头"}：${camera}。`,
                `${video ? "节奏、光线与完成方式" : "光线、材质与完成度"}：${finish}。`,
                `必须遵守：${constraints}。`,
            ].join("\n"),
    };
}

